const entries = await Promise.all(
  images.map(async ([id, relativePath]) => {
    const bytes = await readFile(resolve(root, relativePath));
    return [id, `data:image/jpeg;base64,${bytes.toString("base64")}`];
  })
);

const source = `// This file is generated by scripts/generate-image-assets.mjs.
// Do not edit directly.
export const mapImageDataUris = ${JSON.stringify(Object.fromEntries(entries), null, 2)};

export const getMapImageDataUri = (imageId) => mapImageDataUris[imageId] || "";
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`Generated ${outputPath}`);
