import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src", "assets", "generated", "mapImages.ts");

// src/assets/images/ の原寸PNGから sips で作った縮小JPEG（web/）を使う。
// 縮小コピーの作り直し:
//   for f in uk niigata australia chile; do
//     sips -Z 720 -s format jpeg -s formatOptions 78 \
//       src/assets/images/$f-map.png --out src/assets/images/web/$f-map.jpg
//   done
const images = [
  ["map-uk", "src/assets/images/web/uk-map.jpg"],
  ["map-niigata", "src/assets/images/web/niigata-map.jpg"],
  ["map-australia", "src/assets/images/web/australia-map.jpg"],
  ["map-chile", "src/assets/images/web/chile-map.jpg"]
];

const entries = await Promise.all(
  images.map(async ([id, relativePath]) => {
    const bytes = await readFile(resolve(root, relativePath));
    return [id, `data:image/jpeg;base64,${bytes.toString("base64")}`];
  })
);

const source = `// This file is generated by scripts/generate-image-assets.mjs.
// Do not edit directly.
export const mapImageDataUris = ${JSON.stringify(Object.fromEntries(entries), null, 2)};

export const getMapImageDataUri = (imageId) => mapImageDataUris[imageId] || "";
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`Generated ${outputPath}`);
